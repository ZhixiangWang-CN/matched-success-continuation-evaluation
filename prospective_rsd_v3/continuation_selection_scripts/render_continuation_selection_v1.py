#!/usr/bin/env python3
"""Render the frozen continuation-selection analysis for paper integration."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


def pct(value: float) -> str:
    return f"{100 * value:.2f}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--analysis", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()

    data = json.loads(args.analysis.read_text())
    args.output_dir.mkdir(parents=True, exist_ok=True)
    primary = data["primary"]
    static = data["static_baseline"]
    families = data["families"]

    csv_path = args.output_dir / "continuation_selection_family_results.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=[
            "family", "n_candidates", "continuation_value",
            "current_success_random_value", "shortest_value",
            "continuation_minus_random", "continuation_minus_shortest",
            "continuation_regret",
        ])
        writer.writeheader()
        for row in families:
            writer.writerow({key: row[key] for key in writer.fieldnames})

    table_lines = [
        r"\begin{tabular}{@{}lrrrr@{}}",
        r"\toprule",
        r"Family & Candidates & Continuation & Current-success & Shortest \\",
        r"\midrule",
    ]
    for row in families:
        table_lines.append(
            f"{row['family'].capitalize()} & {row['n_candidates']} & "
            f"{pct(row['continuation_value'])}\\% & "
            f"{pct(row['current_success_random_value'])}\\% & "
            f"{pct(row['shortest_value'])}\\% \\\\"
        )
    table_lines.extend([
        r"\midrule",
        (
            f"Equal-family mean & -- & {pct(primary['continuation_selected_value'])}\\% & "
            f"{pct(primary['current_success_random_value'])}\\% & {pct(static['shortest_value'])}\\% "
            + r"\\"
        ),
        r"\bottomrule",
        r"\end{tabular}",
    ])
    (args.output_dir / "continuation_selection_family_table.tex").write_text("\n".join(table_lines) + "\n")

    ci = primary["family_cluster_bootstrap_95_ci"]
    static_ci = static["family_cluster_bootstrap_95_ci"]
    macros = rf"""% Auto-generated by render_continuation_selection_v1.py
\newcommand{{\SelectionRows}}{{{data['coverage']['rows']}}}
\newcommand{{\SelectionFamilies}}{{{data['coverage']['families']}}}
\newcommand{{\SelectionStates}}{{{data['coverage']['states']}}}
\newcommand{{\SelectionFutures}}{{{data['coverage']['futures']}}}
\newcommand{{\SelectionContinuation}}{{{pct(primary['continuation_selected_value'])}\%}}
\newcommand{{\SelectionRandom}}{{{pct(primary['current_success_random_value'])}\%}}
\newcommand{{\SelectionEffect}}{{{pct(primary['effect'])}}}
\newcommand{{\SelectionEffectLo}}{{{pct(ci[0])}}}
\newcommand{{\SelectionEffectHi}}{{{pct(ci[1])}}}
\newcommand{{\SelectionP}}{{{primary['random_selection_p_one_sided']:.4f}}}
\newcommand{{\SelectionShortest}}{{{pct(static['shortest_value'])}\%}}
\newcommand{{\SelectionStaticEffect}}{{{pct(static['effect'])}}}
\newcommand{{\SelectionStaticEffectLo}}{{{pct(static_ci[0])}}}
\newcommand{{\SelectionStaticEffectHi}}{{{pct(static_ci[1])}}}
"""
    (args.output_dir / "continuation_selection_numbers.tex").write_text(macros)

    gate = "PASS" if primary["claim_gate_pass"] else "NO-GO"
    report = f"""# Frozen held-out continuation-selection result

- Protocol: `{data['protocol']}`
- Consumer: `{data['consumer']}`
- Coverage: {data['coverage']['rows']}/{data['coverage']['expected_rows']} rows,
  {data['coverage']['states']} states, {data['coverage']['families']} families,
  {data['coverage']['futures']} held-out futures, {data['coverage']['repeats']} repeats
- Claim gate: **{gate}**
- Continuation-selected held-out success: {pct(primary['continuation_selected_value'])}%
- Current-success random-choice expectation: {pct(primary['current_success_random_value'])}%
- Primary effect: {pct(primary['effect'])} percentage points
  (family-cluster bootstrap 95% CI [{pct(ci[0])}, {pct(ci[1])}])
- Exact one-sided random-selection p: {primary['random_selection_p_one_sided']:.6f}
  over {primary['random_selection_combinations']:,} possible choices
- Shortest-state baseline: {pct(static['shortest_value'])}%
- Continuation-selected minus shortest: {pct(static['effect'])} percentage points
  (family-cluster bootstrap 95% CI [{pct(static_ci[0])}, {pct(static_ci[1])}])

The claim gate was frozen before held-out execution. The result supports a
decision-utility claim only when the primary effect is positive and the exact
one-sided random-selection p-value is below 0.05.
"""
    (args.output_dir / "CONTINUATION_SELECTION_RESULT.md").write_text(report)

    labels = [row["family"] for row in families] + ["Equal-family\nmean"]
    continuation = [row["continuation_value"] for row in families] + [primary["continuation_selected_value"]]
    random = [row["current_success_random_value"] for row in families] + [primary["current_success_random_value"]]
    shortest = [row["shortest_value"] for row in families] + [static["shortest_value"]]
    x = np.arange(len(labels))
    width = 0.24
    fig, ax = plt.subplots(figsize=(7.2, 3.3))
    ax.bar(x - width, continuation, width, label="Continuation-selected", color="#176B87")
    ax.bar(x, random, width, label="Current-success random", color="#9AA5B1")
    ax.bar(x + width, shortest, width, label="Shortest state", color="#D97706")
    ax.set_ylim(0, 1.04)
    ax.set_ylabel("Held-out continuation success")
    ax.set_xticks(x, labels, rotation=25, ha="right")
    ax.grid(axis="y", alpha=0.25, linewidth=0.7)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False, ncol=3, loc="upper center", bbox_to_anchor=(0.5, 1.18))
    fig.tight_layout()
    fig.savefig(args.output_dir / "continuation_selection.pdf", bbox_inches="tight")
    fig.savefig(args.output_dir / "continuation_selection.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


if __name__ == "__main__":
    main()
